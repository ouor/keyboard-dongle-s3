#define MIRROR_Y true
#define INVERT true  // IPS panel

static esp_lcd_panel_handle_t s_panel;
static uint16_t *s_fb;  // RGB565, byte-swapped for SPI
static SemaphoreHandle_t s_lock, s_done;  // s_done: the DMA is finished with s_fb

static bool on_done(esp_lcd_panel_io_handle_t io, esp_lcd_panel_io_event_data_t *e, void *ctx)
{
    BaseType_t woken = pdFALSE;
    xSemaphoreGiveFromISR(s_done, &woken);
    return woken == pdTRUE;
}

