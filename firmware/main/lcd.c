// Draws up to `max` chars at scale `s`; returns chars drawn. shortcut: non-ASCII (e.g. Korean names) shows as '?'.
static int text(int x, int y, int s, uint16_t color, const char *str, int max)
{
    uint16_t c565 = (uint16_t)(color << 8 | color >> 8);
    int n = 0;
    for (; *str && n < max; str++, n++, x += 6 * s) {
        unsigned ch = (unsigned char)*str;
        const uint8_t *g = FONT[(ch < 0x20 || ch > 0x7E ? '?' : ch) - 0x20];
        for (int col = 0; col < 5; col++) {
            for (int row = 0; row < 8; row++) {
                if (!(g[col] >> row & 1)) {
                    continue;
                }
                for (int dy = 0; dy < s; dy++) {
                    for (int dx = 0; dx < s; dx++) {
                        int px = x + col * s + dx, py = y + row * s + dy;
                        if (px < W && py < H) {
                            s_fb[py * W + px] = c565;
                        }
                    }
                }
            }
        }
    }
    return n;
}

void lcd_show(const char *state, uint16_t color, const char *name, const char *addr)
{
    if (!s_panel) {
        return;
    }
    xSemaphoreTake(s_lock, portMAX_DELAY);
    memset(s_fb, 0, W * H * 2);
    text(2, 2, 2, color, state, 13);
    int n = text(2, 24, 2, 0xFFFF, name, 13);  // name: 2 lines x 13 chars
    if ((int)strlen(name) > n) {
        text(2, 42, 2, 0xFFFF, name + n, 13);
    }
    text(2, 68, 1, LCD_GRAY, addr, 26);
    if (esp_lcd_panel_draw_bitmap(s_panel, 0, 0, W, H, s_fb) == ESP_OK) {
        xSemaphoreTake(s_done, pdMS_TO_TICKS(100));
    }
    xSemaphoreGive(s_lock);
}

void lcd_init(void)
{
    const spi_bus_config_t bus = {.sclk_io_num = 10, .mosi_io_num = 11, .miso_io_num = -1, .quadwp_io_num = -1, .quadhd_io_num = -1,
                                  .max_transfer_sz = W * H * 2};
    const esp_lcd_panel_io_spi_config_t io_cfg = {.cs_gpio_num = 12, .dc_gpio_num = 13, .pclk_hz = 26 * 1000 * 1000,
                                                  .lcd_cmd_bits = 8, .lcd_param_bits = 8, .spi_mode = 0, .trans_queue_depth = 4,
                                                  .on_color_trans_done = on_done};
    const esp_lcd_panel_dev_config_t panel_cfg = {.reset_gpio_num = 14, .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_BGR, .bits_per_pixel = 16};
    esp_lcd_panel_io_handle_t io;

    s_fb = heap_caps_malloc(W * H * 2, MALLOC_CAP_DMA);
    s_lock = xSemaphoreCreateMutex();
    s_done = xSemaphoreCreateBinary();
    if (!s_fb || spi_bus_initialize(SPI2_HOST, &bus, SPI_DMA_CH_AUTO) != ESP_OK ||
        esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)SPI2_HOST, &io_cfg, &io) != ESP_OK ||
        esp_lcd_new_panel_st7789(io, &panel_cfg, &s_panel) != ESP_OK) {
        ESP_LOGE("lcd", "init failed");  // the dongle works without its screen
        s_panel = NULL;
        return;
    }
    esp_lcd_panel_reset(s_panel);
    esp_lcd_panel_init(s_panel);
    esp_lcd_panel_invert_color(s_panel, INVERT);
    esp_lcd_panel_swap_xy(s_panel, true);
    esp_lcd_panel_mirror(s_panel, MIRROR_X, MIRROR_Y);
    esp_lcd_panel_set_gap(s_panel, GAP_X, GAP_Y);
    esp_lcd_panel_disp_on_off(s_panel, true);
}
