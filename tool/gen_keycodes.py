"""keycodes.json -> firmware/main/keycodes.h + tool/KeyCodes.cs (run from anywhere)."""
import json
import pathlib

here = pathlib.Path(__file__).resolve().parent
src = json.loads((here / "keycodes.json").read_text(encoding="utf-8"))
pages = {"keyboard": 0, "consumer": 1}
keys = [(name, pages[page], usage) for page in pages for name, usage in src[page].items()]

names = [k[0] for k in keys]
assert len(names) == len(set(n.lower() for n in names)), "duplicate key name (case-insensitive)"
assert all(n.replace("_", "").isalnum() for n in names), "key names must be alphanumeric"
assert all(0 < u <= (0xFF if p == 0 else 0xFFFF) for _, p, u in keys), "usage out of range"

hdr = ["// generated by tool/gen_keycodes.py from tool/keycodes.json - do not edit", "#pragma once", "#include <stdint.h>", "",
       "enum { KC_PAGE_KEYBOARD = 0, KC_PAGE_CONSUMER = 1 };",
       "typedef struct { const char *name; uint8_t page; uint16_t usage; } keycode_t;", "",
       "static const keycode_t KEYCODES[] = {"]
hdr += [f'    {{"{n}", {p}, 0x{u:02X}}},' for n, p, u in keys]
hdr += ["};", "#define KEYCODES_COUNT (sizeof(KEYCODES) / sizeof(KEYCODES[0]))", ""]
(here.parent / "firmware" / "main" / "keycodes.h").write_text("\n".join(hdr), encoding="utf-8")

cs = ["// generated by tool/gen_keycodes.py from tool/keycodes.json - do not edit",
      "static class KeyCodes", "{", "    public static readonly string[] Names = {"]
cs += [f'        "{n}",' for n in names]
cs += ["    };", "}", ""]
(here / "KeyCodes.cs").write_text("\n".join(cs), encoding="utf-8")
print(f"{len(keys)} keycodes generated")
